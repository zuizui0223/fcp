#!/usr/bin/env python3
"""Score a future *independent human* audit without treating blank forms as data.

Input reviewer sheets are generated by fcp_image_pair_label_validation_audit_20261122.py.
The key must NOT be supplied to the reviewers; it is supplied ONLY on unblinding.

python scripts/analysis/fcp_two_reader_petal_adjudication_20261122.py \
  --reviewer-a reviewer_A_blind_128_pairs.csv \
  --reviewer-b reviewer_B_blind_128_pairs.csv \
  --key UNBLIND_AFTER_TWO_REVIEWS_original_128_pair_key.csv \
  --out-dir /tmp/fcp-petal-human-review

The program computes NO corrected estimate until all pairs have 2 agreed human
scores or 3rd-reader adjudication, even for pairs marked unreadable.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import random
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "manuscripts/climate_colour/Table_S11_pair_audit.csv"
COLOURS = {"white","yellow_orange","red_pink","blue_purple"}
BOOL = {"yes","no","uncertain"}
BASE_WHITE = 2.63
BASE_DIFFERENCE = -0.01
SEED = 20261122


def check(ok, msg):
    if not ok:
        raise AssertionError("FCP_BOTANICAL_ADJUDICATION: "+str(msg))


def load(path):
    with path.open(newline="",encoding="utf8") as f:
        return list(csv.DictReader(f))


def rows_indexed(path, key):
    r=load(path)
    ids=[x[key] for x in r]
    check(len(r)==128 and len(set(ids))==128 and all(ids),
          f"{path}: exactly 128 unique blind IDs required")
    return {x[key]:x for x in r}


def is_completed(r):
    keys=["photo_A_open_corolla_visible","photo_B_open_corolla_visible",
          "same_homologous_open_floral_organ","same_flower_stage",
          "image_quality_sufficient","photo_A_primary_open_petal_colour",
          "photo_B_primary_open_petal_colour"]
    return any((r.get(k) or "").strip() for k in keys)


def score(r):
    if not is_completed(r):
        return None
    flags=["photo_A_open_corolla_visible","photo_B_open_corolla_visible",
           "same_homologous_open_floral_organ","same_flower_stage",
           "image_quality_sufficient"]
    for f in flags:
        v=(r.get(f) or "").strip().lower()
        check(v in BOOL, "fully scored review needs "+f+" = yes/no/uncertain")
    a=(r.get("photo_A_primary_open_petal_colour") or "").strip().lower()
    b=(r.get("photo_B_primary_open_petal_colour") or "").strip().lower()
    check(a in COLOURS|{"unknown",""}, "unknown first-petal colour token")
    check(b in COLOURS|{"unknown",""}, "unknown second-petal colour token")
    comparable=(all(r.get(f,"").strip().lower()=="yes" for f in flags)
                and a in COLOURS and b in COLOURS)
    if comparable:
        return {"readable":True,"a":a,"b":b,
                "white":(int(a=="white")+int(b=="white"))/2,
                "mismatch":int(a!=b)}
    return {"readable":False,"a":None,"b":None,
            "white":None,"mismatch":None}


def quant(a,p):
    a=sorted(a)
    ix=(len(a)-1)*p
    lo=math.floor(ix)
    return a[lo]+(a[min(lo+1,len(a)-1)]-a[lo])*(ix-lo)


def tail_mean(rows,field):
    q={}
    for t in ("-1","1"):
        a=[r for r in rows if r["tail"]==t]
        den=sum(r["weight"] for r in a)
        check(den>0,"one thermal tail has no weighted pair support")
        q[t]=sum(r["weight"]*r[field] for r in a)/den
    return 100*(q["1"]-q["-1"])


def contrasts(rows):
    original_w=tail_mean(rows,"source_white")
    corrected_w=tail_mean(rows,"review_white")
    original_d=tail_mean(rows,"source_diff")
    corrected_d=tail_mean(rows,"review_diff")
    return {
        "white_shift_pp": corrected_w-original_w,
        "mismatch_shift_pp": corrected_d-original_d,
        "corrected_white_pp_from_rounded_full_frame": BASE_WHITE+corrected_w-original_w,
        "corrected_mismatch_pp_from_rounded_full_frame": BASE_DIFFERENCE+corrected_d-original_d
    }


def resample(rows,reps):
    rng=random.Random(SEED)
    strata={}
    for row in rows:
        key=(row["tail"],row["source_diff"])
        strata.setdefault(key,[]).append(row)
    check(len(strata)==4 and all(len(g)==32 for g in strata.values()),
          "the 4x32 matched source audit strata have changed")
    white,mismatch=[],[]
    for _ in range(reps):
        drawn=[rng.choice(group) for group in strata.values()
               for _ in range(len(group))]
        s=contrasts(drawn)
        white.append(s["corrected_white_pp_from_rounded_full_frame"])
        mismatch.append(s["corrected_mismatch_pp_from_rounded_full_frame"])
    return {"reps":reps, "seed":SEED,
            "white_95":[quant(white,.025),quant(white,.975)],
            "mismatch_95":[quant(mismatch,.025),quant(mismatch,.975)],
            "scope":"fixed source sample frames, bootstrap 4x32 strata; no original fitting uncertainty"}


def main(args):
    A=rows_indexed(args.reviewer_a,"blind_pair_id")
    B=rows_indexed(args.reviewer_b,"blind_pair_id")
    key=rows_indexed(args.key,"blind_pair_id")
    check(A.keys()==B.keys()==key.keys(),"reviewer IDs / key do not match")
    original=rows_indexed(SOURCE,"id")
    check(len(original)==128,"source table changed")
    adjudicator=rows_indexed(args.adjudicator,"blind_pair_id") if args.adjudicator else None
    if adjudicator is not None:
        check(adjudicator.keys()==key.keys(),"adjudicator IDs drift")
    statuses=Counter()
    result=[]
    conflicts=[]
    reviewed_A=reviewed_B=0
    for bid in sorted(key):
        k=key[bid]
        source=original[k["original_source_pair_id"]]
        check(k["inat_taxon_id"]==source["inat_taxon_id"] and
              k["left_photo_id"]==source["left_photo_id"] and
              k["right_photo_id"]==source["right_photo_id"],
              "source photo/key linkage changed")
        check(A[bid]["photo_A_url"]==B[bid]["photo_A_url"] and
              A[bid]["photo_B_url"]==B[bid]["photo_B_url"],
              "reviewers were shown different image order for same pair")
        x,y=score(A[bid]),score(B[bid])
        reviewed_A+=x is not None
        reviewed_B+=y is not None
        if x is None or y is None:
            state="pending"
            final=None
        elif x==y:
            state="two_reader_consensus"
            final=x
        else:
            z=score(adjudicator[bid]) if adjudicator else None
            if z is None:
                state="adjudication_required"
                final=None
            else:
                state="third_reader_adjudicated"
                final=z
        statuses[state]+=1
        if state in ("pending","adjudication_required"):
            conflicts.append({
                "blind_pair_id":bid,
                "photo_A_url":A[bid]["photo_A_url"],
                "photo_B_url":A[bid]["photo_B_url"],
                "state":state,
                "reason":"human scoring not complete or reviewers disagree"
            })
        source_white=float(source["white"])
        source_diff=int(source["original_pair_mismatch"])
        result.append({
            "blind_id":bid,"tail":source["tail"],
            "source_diff":source_diff,"source_white":source_white,
            "weight":float(source["stratum_weight"]),
            "final_readable":None if final is None else final["readable"],
            "review_white":None if final is None else (
                final["white"] if final["readable"] else source_white),
            "review_diff":None if final is None else (
                final["mismatch"] if final["readable"] else source_diff),
            "state":state
        })
    done=not conflicts
    out={"schema":"fcp_independent_human_petal_pair_adjudication_v1",
         "status":"HUMAN_REVIEW_COMPLETE" if done else "NOT_YET_VALIDATED",
         "counts":{"pairs":128,"reviewed_A":reviewed_A,"reviewed_B":reviewed_B,
                   "states":dict(statuses),"n_pending_or_conflicting":len(conflicts)},
         "n_final_readable":sum(r["final_readable"] is True for r in result),
         "n_final_unreadable":sum(r["final_readable"] is False for r in result),
         "selection_notice":"not population classification accuracy: selected 4x32 tail/agreement pairs; unreadables retain original",
         "source_pair_table":str(SOURCE.relative_to(ROOT)),
         "biological_claim_guard":"No heritable morph, petal selection, or original-photo refit established",
         "corrected_estimates":None,
         "bootstrap":None}
    if done:
        out["corrected_estimates"]=contrasts(result)
        out["bootstrap"]=resample(result,args.bootstrap)
    args.out_dir.mkdir(parents=True,exist_ok=True)
    (args.out_dir/"human_review_status_and_result.json").write_text(
        json.dumps(out,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    with (args.out_dir/"REQUIRES_BOTANIST_REVIEW_OR_ADJUDICATION.csv").open(
            "w",newline="",encoding="utf-8") as f:
        fieldnames=["blind_pair_id","photo_A_url","photo_B_url","state","reason"]
        w=csv.DictWriter(f,fieldnames=fieldnames)
        w.writeheader()
        w.writerows(conflicts)
    print(json.dumps({"status":out["status"],"counts":out["counts"],
                      "corrected_estimates":out["corrected_estimates"],
                      "bootstrap":out["bootstrap"]},indent=2))
    # For automated source CI a blank-human input must be actively rejected as a
    # completed biological audit, but returning 0 supports a separate status report.
    if args.require_complete and not done:
        raise SystemExit("NOT_VALIDATED: two human readers and adjudication still required")


if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--reviewer-a",type=Path,required=True)
    p.add_argument("--reviewer-b",type=Path,required=True)
    p.add_argument("--key",type=Path,required=True)
    p.add_argument("--adjudicator",type=Path)
    p.add_argument("--out-dir",type=Path,required=True)
    p.add_argument("--bootstrap",type=int,default=5000)
    p.add_argument("--require-complete",action="store_true")
    main(p.parse_args())
